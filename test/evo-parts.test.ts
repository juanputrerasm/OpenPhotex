/*
  4x4 Evolution 2's parts (OpenMTM2 docs/EVO2_PHYSICS.md §2.1).
*/
import test from "node:test";
import assert from "node:assert/strict";
import { evoSim, parseEvoParts } from "../src/index.ts";

const TEXT = [
  "partCount", "3",
  "--- Part 1 ---", "Name", "Supercharger", "Code", "Supercharger", "Type", "Engine", "Cost", "2995",
  "Aero Mod", "0.0", "Brake Mod", "0.0", "CG Mod", "0.0", "Tire CF Mod", "0.0", "Torque Mod", "0.2", "Weight Mod", "50",
  "Models", "", "Prerequisite", "", "Incompatible", "", "Incompatible Trucks", "", "Team Requirement", "None", "Notes", "",
  "--- Part 2 ---", "Name", "Carbon body", "Code", "CarbonFiberBody", "Type", "Chassis", "Cost", "9000",
  "Aero Mod", "-0.05", "Brake Mod", "0.0", "CG Mod", "0.0", "Tire CF Mod", "0.0", "Torque Mod", "0.0", "Weight Mod", "-0.03",
  "Models", "", "Prerequisite", "", "Incompatible", "", "Incompatible Trucks", "", "Team Requirement", "None", "Notes", "",
  "--- Part 3 ---", "Name", "12 lift", "Code", "12LiftKit", "Type", "Suspension", "Cost", "1500",
  "Aero Mod", "0.0", "Brake Mod", "0.0", "CG Mod", "0.0", "Tire CF Mod", "0.02", "Torque Mod", "0.0", "Weight Mod", "0.0",
  "Models", "", "Prerequisite", "", "Incompatible", "", "Incompatible Trucks", "", "Team Requirement", "None", "Notes", "",
  "signature: 0 0 // WARNING: Do not edit this file",
].join("\r\n");

test("PARTS.TXT reads into parts with their six modifiers", () => {
  const parts = parseEvoParts(TEXT);
  assert.equal(parts.length, 3);
  assert.deepEqual([parts[0]!.code, parts[0]!.torqueMod, parts[0]!.weightMod], ["Supercharger", 0.2, 50]);
  assert.equal(parts[1]!.aeroMod, -0.05);
  assert.equal(parts[2]!.tireCfMod, 0.02);
});

test("fitted parts: drag, torque, weight in pounds and as a share, a lift kit (0x5eaa40)", () => {
  const parts = parseEvoParts(TEXT);
  const base: evoSim.EvoVehicleSpec = {
    ...evoSim.evoSpecFromTrk({ specs: {}, wheelAnchors: {}, scrapePoints: [], game: 2 } as never),
    cd: 0.4, dryWeightLb: 4000, axleWeightLb: [500, 500], torqueTable: [100, 200], wheelAnchors: [[2, -1, 4], [-2, -1, 4], [2, -1, -4], [-2, -1, -4]],
  };
  const { spec, liftFt, tireModelBase } = evoSim.applyEvoParts(base, ["Supercharger", "CarbonFiberBody", "12LiftKit", "NoSuchPart"], parts);
  assert.ok(Math.abs(spec.cd - 0.38) < 1e-9);
  assert.deepEqual(spec.torqueTable.map((t) => Math.round(t * 1000) / 1000), [120, 240]);
  // 4000 + (4000 + 1000) * -0.03 + 50; the tire CF modifier has no effect.
  assert.ok(Math.abs(spec.dryWeightLb - 3900) < 1e-9);
  assert.equal(liftFt, 1);
  assert.equal(spec.wheelAnchors[0]![1], -2);
  assert.equal(tireModelBase, null);
  assert.deepEqual(spec.tireCF, base.tireCF);
});
